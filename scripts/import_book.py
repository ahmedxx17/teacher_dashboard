#!/usr/bin/env python3
"""
scripts/import_book.py
Ingests structured curriculum JSON into Supabase PostgreSQL.

Usage:
    python import_book.py --json data/9_physics_en.json

Features:
- Idempotent upserts on subjects, chapters, and topics.
- Uses SUPABASE_SERVICE_ROLE_KEY to bypass RLS policies.
- Completely safe to re-run without duplicating records.
"""

import os
import sys
import json
import argparse
from typing import Dict, Any

from dotenv import load_dotenv

# Try loading from current directory or parent directory
load_dotenv()
load_dotenv(os.path.join(os.path.dirname(__file__), ".env"))

try:
    from supabase import create_client, Client
except ImportError:
    print("Error: supabase-py is not installed. Run: pip install supabase")
    sys.exit(1)


def get_supabase_client() -> Client:
    url = os.getenv("SUPABASE_URL")
    service_role_key = os.getenv("SUPABASE_SERVICE_ROLE_KEY")

    if not url or not service_role_key:
        print("\n❌ Error: Missing Supabase credentials.")
        print("Please set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env or environment variables.")
        sys.exit(1)

    return create_client(url, service_role_key)


def import_curriculum(client: Client, data: Dict[str, Any]) -> None:
    subject_name = data.get("subject")
    class_level = data.get("class")
    medium = data.get("medium", "en")
    book_version = data.get("book_version", "PCTB")
    chapters_data = data.get("chapters", [])

    print(f"\n🚀 Importing Curriculum: {subject_name} | Class {class_level} | Medium: {medium.upper()}")

    # 1. Upsert Subject
    subject_payload = {
        "name": subject_name,
        "class": class_level,
        "medium": medium,
        "book_version": book_version,
    }

    try:
        # Upsert subject based on unique constraint (name, class, medium)
        sub_resp = client.table("subjects").upsert(
            subject_payload,
            on_conflict="name,class,medium"
        ).execute()

        if not sub_resp.data:
            # Fallback query if upsert returned empty data
            sub_resp = client.table("subjects").select("id").match({
                "name": subject_name,
                "class": class_level,
                "medium": medium
            }).execute()

        subject_id = sub_resp.data[0]["id"]
        print(f"✅ Subject saved/updated: {subject_name} (ID: {subject_id})")

    except Exception as e:
        print(f"❌ Failed to upsert subject: {e}")
        sys.exit(1)

    total_chapters = 0
    total_topics = 0

    # 2. Iterate and Upsert Chapters
    for chap in chapters_data:
        chap_num = chap["number"]
        chap_title = chap["title"]
        topics_list = chap.get("topics", [])

        chap_payload = {
            "subject_id": subject_id,
            "number": chap_num,
            "title": chap_title
        }

        try:
            chap_resp = client.table("chapters").upsert(
                chap_payload,
                on_conflict="subject_id,number"
            ).execute()

            if not chap_resp.data:
                chap_resp = client.table("chapters").select("id").match({
                    "subject_id": subject_id,
                    "number": chap_num
                }).execute()

            chapter_id = chap_resp.data[0]["id"]
            total_chapters += 1

            # 3. Upsert Topics in this Chapter
            chapter_topic_count = 0
            for top in topics_list:
                top_payload = {
                    "chapter_id": chapter_id,
                    "title": top["title"],
                    "order_index": top["order_index"],
                    "start_page": top.get("start_page"),
                    "end_page": top.get("end_page"),
                    "text": top.get("text", "")
                }

                client.table("topics").upsert(
                    top_payload,
                    on_conflict="chapter_id,order_index"
                ).execute()
                chapter_topic_count += 1
                total_topics += 1

            print(f"   📁 Chapter {chap_num}: '{chap_title}' -> {chapter_topic_count} topics upserted.")

        except Exception as e:
            print(f"❌ Error importing chapter {chap_num}: {e}")

    print("\n" + "=" * 60)
    print("🎉 Import Complete!")
    print(f"   Subject:  {subject_name} (Class {class_level})")
    print(f"   Chapters: {total_chapters}")
    print(f"   Topics:   {total_topics}")
    print("   Data is now live and available in the Teacher Dashboard web app.")
    print("=" * 60 + "\n")


def main():
    parser = argparse.ArgumentParser(
        description="Upsert structured curriculum JSON into Supabase PostgreSQL."
    )
    parser.add_argument(
        "--json",
        required=True,
        help="Path to the JSON file generated by parse_book.py (e.g. data/9_physics_en.json)"
    )

    args = parser.parse_args()

    if not os.path.exists(args.json):
        print(f"Error: JSON file '{args.json}' does not exist.")
        sys.exit(1)

    with open(args.json, "r", encoding="utf-8") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError as err:
            print(f"Error: Failed to parse JSON file: {err}")
            sys.exit(1)

    client = get_supabase_client()
    import_curriculum(client, data)


if __name__ == "__main__":
    main()
